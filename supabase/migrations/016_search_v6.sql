-- AffiliateOS Search Engine v6 — three intent layers + richer qualification
--
-- The old keyword pool burned out after ~a month: 1729 of 1985 finds were
-- already-known domains. This replaces the pool wholesale and moves keywords out
-- of code into a table, so their yield can be measured and dead ones retired
-- automatically instead of silently dragging the pipeline down.
--
-- Idempotent: safe to re-run.
