-- ── Search provenance + qualification fields on leads ──────────────────────
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS search_layer   TEXT;     -- A|B|C
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS source_keyword TEXT;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS source_page    INTEGER;

ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS audience_owner        BOOLEAN;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS monetization_signal   BOOLEAN;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS monetization_evidence TEXT;
ALTER TABLE public.leads ADD COLUMN IF NOT EXISTS has_partnership_path  BOOLEAN;

CREATE INDEX IF NOT EXISTS leads_search_layer_idx ON public.leads (search_layer);

-- ── Keyword pool with per-key yield tracking ───────────────────────────────
CREATE TABLE IF NOT EXISTS public.keywords (
  id            BIGSERIAL PRIMARY KEY,
  preset        TEXT NOT NULL,
  layer         TEXT NOT NULL,              -- A = player intent, B = publisher, C = competitor footprint
  keyword       TEXT NOT NULL,
  lang          TEXT,
  active        BOOLEAN DEFAULT TRUE,
  archived_at   TIMESTAMPTZ,
  runs          INTEGER DEFAULT 0,
  urls_found    INTEGER DEFAULT 0,
  leads_created INTEGER DEFAULT 0,
  hot_leads     INTEGER DEFAULT 0,          -- fit_score >= 70
  last_run_at   TIMESTAMPTZ,
  created_at    TIMESTAMPTZ DEFAULT now(),
  UNIQUE (preset, keyword)
);
CREATE INDEX IF NOT EXISTS keywords_active ON public.keywords (preset, layer) WHERE active = TRUE;

ALTER TABLE public.keywords DISABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.keywords TO anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.keywords_id_seq TO anon, authenticated;


