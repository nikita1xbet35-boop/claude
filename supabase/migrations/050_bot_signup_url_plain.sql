-- 050 — ссылка регистрации без параметра ref
--
-- 049 ставила 'https://1xaffiliate.org/newreg?ref={ref}', собрав шаблон по
-- примеру из ТЗ §3.2. Уточнение от Ника: 1xaffiliate.org/newreg — это уже
-- готовая сокращённая реферальная ссылка, а не голый адрес формы. Дописывать
-- к ней свой query-параметр незачем и рискованно: сокращатель либо его
-- проигнорирует, либо не переживёт лишний хвост в адресе.
--
-- ── Чем за это платим ───────────────────────────────────────────────────────
-- Ссылка становится одинаковой для всех. Это значит, что на стороне
-- 1xPartners регистрацию нельзя связать ни с конкретным ботом, ни с
-- конкретным человеком — партнёрка увидит только общий поток по этой ссылке.
--
-- На нашей стороне привязка сохраняется полностью: bot_leads по-прежнему
-- пишет bot_slug, tg_user_id, tg_username и ref_code (tg_{slug}_{id}) в момент
-- выдачи. То есть «сколько выдал каждый бот» и «кому именно» мы знаем, а
-- «кто из них дошёл до регистрации» — нет. Если такая сводка понадобится,
-- вернуть параметр можно одним UPDATE: код подставляет {ref} везде, где он
-- встретится в шаблоне, и ничего не меняет, когда его нет.

UPDATE public.bot_configs
   SET signup_url_tpl = 'https://1xaffiliate.org/newreg';

-- ── Проверка ────────────────────────────────────────────────────────────────
-- {ref} здесь НЕ проверяется — в отличие от 049, где его отсутствие было
-- ошибкой. Теперь его отсутствие и есть намерение, а проверять осталось одно:
-- что ссылка вообще задана. Пустой шаблон означает бота, который на главную
-- кнопку отвечает «ссылка не настроена», и заметить это можно только вручную.
DO $$
DECLARE n_empty INT; sample TEXT;
BEGIN
  SELECT count(*) INTO n_empty FROM public.bot_configs WHERE coalesce(signup_url_tpl,'') = '';
  IF n_empty > 0 THEN
    RAISE EXCEPTION 'у % ботов пустая ссылка регистрации — их главная кнопка не сработает', n_empty;
  END IF;

  SELECT DISTINCT signup_url_tpl INTO sample FROM public.bot_configs;
  RAISE NOTICE 'ссылка у всех 6 ботов: %', sample;
END $$;
