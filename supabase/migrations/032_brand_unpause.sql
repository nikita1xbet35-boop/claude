-- ПОЧЕМУ ОТДЕЛЬНЫМ ШАГОМ, А НЕ ВМЕСТЕ С ТЕКСТОМ ПИСЬМА
-- Деплой применяет миграции ДО выкатки функций. Сними мы паузу в том же
-- коммите, что и текст, между этими двумя шагами открылось бы окно секунд в
-- девяносто: очередь уже живая, а process-queue ещё со старым письмом. За это
-- окно 308 бренд-лидам ушёл бы текст основного пайплайна — «strong work in
-- Nigeria» человеку, который перехватывает «mostbet apk». Это ровно тот сбой,
-- ради предотвращения которого пауза и заводилась в v8.
--
-- Поэтому: сначала коммит c847ab7 с текстом, подтверждение что process-queue
-- реально пересобран («Deployed Functions ... process-queue» в логе деплоя),
-- и только теперь эта миграция.
--
-- Что дальше делает система сама: generate-queue-brand наполняет очередь в
-- пределах 50 писем в сутки, отбирая по позиции в брендовой выдаче и наличию
-- APK, и исключая occupied / suspected_official / parked / brand_mismatch.
--
-- Обратно ставится одной кнопкой на вкладке Brand — тумблер «Пауза».
-- ═══════════════════════════════════════════════════════════════════════════

